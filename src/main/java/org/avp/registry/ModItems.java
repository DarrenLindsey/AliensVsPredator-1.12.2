    /** A plain item with no special behaviour (crafting parts, ingots, ...). */
    private static DeferredItem<Item> simple(String id, Tab tab, int maxStack)
    {
        DeferredItem<Item> item = ITEMS.register(id, () -> new Item(new Item.Properties().stacksTo(maxStack)));
        tab.add(item);
        return item;
    }

    /**
     * A food item.
     * @param nutrition  half-drumsticks restored (old ItemFood "amount")
     * @param saturation old ItemFood "saturation" (default was 0.6)
     * @param meat       old ItemFood "isWolfFood" - only a reminder now; wolf food is the minecraft:meat item tag
     * @param always     can be eaten when not hungry (old setAlwaysEdible)
     */
    private static DeferredItem<Item> food(String id, int nutrition, float saturation, boolean meat, boolean always)
    {
        DeferredItem<Item> item = ITEMS.register(id, () -> {
            FoodProperties.Builder food = new FoodProperties.Builder().nutrition(nutrition).saturationModifier(saturation);
            if (always) food = food.alwaysEdible();
            return new Item(new Item.Properties().food(food.build()));
        });
        Tab.MAIN.add(item);
        return item;
    }

