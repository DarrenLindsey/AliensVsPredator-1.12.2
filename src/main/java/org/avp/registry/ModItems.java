    /** A plain item with no special behaviour (crafting parts, ingots, ...). */
    private static RegistryObject<Item> simple(String id, Tab tab, int maxStack)
    {
        RegistryObject<Item> item = ITEMS.register(id, () -> new Item(new Item.Properties().stacksTo(maxStack)));
        tab.add(item);
        return item;
    }

    /**
     * A food item.
     * @param nutrition  half-drumsticks restored (old ItemFood "amount")
     * @param saturation old ItemFood "saturation" (default was 0.6)
     * @param meat       old ItemFood "isWolfFood" - wolves can eat it
     * @param always     can be eaten when not hungry (old setAlwaysEdible)
     */
    private static RegistryObject<Item> food(String id, int nutrition, float saturation, boolean meat, boolean always)
    {
        RegistryObject<Item> item = ITEMS.register(id, () -> {
            FoodProperties.Builder food = new FoodProperties.Builder().nutrition(nutrition).saturationMod(saturation);
            if (meat) food = food.meat();
            if (always) food = food.alwaysEat();
            return new Item(new Item.Properties().food(food.build()));
        });
        Tab.MAIN.add(item);
        return item;
    }

