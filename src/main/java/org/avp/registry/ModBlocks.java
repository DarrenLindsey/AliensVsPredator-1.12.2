    /** A plain full-cube block that drops itself. */
    private static DeferredBlock<Block> simple(String id, Kind kind, float hardness, float resistance)
    {
        return simple(id, kind, hardness, resistance, 0, false);
    }

    /**
     * @param light      light level the block gives off (0-15)
     * @param seeThrough true for glass/grill blocks (needs "render_type" in the block model too)
     */
    private static DeferredBlock<Block> simple(String id, Kind kind, float hardness, float resistance, int light, boolean seeThrough)
    {
        DeferredBlock<Block> block = BLOCKS.register(id, () -> {
            BlockBehaviour.Properties props = BlockBehaviour.Properties.of()
                    .mapColor(kind.color)
                    .sound(kind.sound)
                    .strength(hardness, resistance)
                    .lightLevel(state -> light);
            if (kind.needsTool) props = props.requiresCorrectToolForDrops();
            if (seeThrough) props = props.noOcclusion();
            return new Block(props);
        });
        withItem(block, Tab.BLOCKS);
        return block;
    }

    /** Registers any block (plus its item) and puts it in a creative tab. */
    private static <B extends Block> DeferredBlock<B> register(String id, Tab tab, Supplier<B> factory)
    {
        DeferredBlock<B> block = BLOCKS.register(id, factory);
        withItem(block, tab);
        return block;
    }

