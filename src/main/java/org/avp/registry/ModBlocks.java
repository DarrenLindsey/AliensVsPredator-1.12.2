    /** A plain full-cube block that drops itself. */
    private static RegistryObject<Block> simple(String id, Kind kind, float hardness, float resistance)
    {
        return simple(id, kind, hardness, resistance, 0, false);
    }

    /**
     * @param light      light level the block gives off (0-15)
     * @param seeThrough true for glass/grill blocks (needs "render_type" in the block model too)
     */
    private static RegistryObject<Block> simple(String id, Kind kind, float hardness, float resistance, int light, boolean seeThrough)
    {
        RegistryObject<Block> block = BLOCKS.register(id, () -> {
            BlockBehaviour.Properties props = BlockBehaviour.Properties.of()
                    .mapColor(kind.color)
                    .sound(kind.sound)
                    .strength(hardness, resistance)
                    .lightLevel(state -> light);
            if (kind.needsTool) props = props.requiresCorrectToolForDrops();
            if (seeThrough) props = props.noOcclusion();
            return new Block(props);
        });
        withItem(block, Tab.BLOCKS);
        return block;
    }

    /** Registers the inventory item for a block and puts it in a creative tab. */
    private static void withItem(RegistryObject<Block> block, Tab tab)
    {
        RegistryObject<Item> item = ModItems.ITEMS.register(block.getId().getPath(), () -> new BlockItem(block.get(), new Item.Properties()));
        tab.add(item);
    }

